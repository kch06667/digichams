/* No original sprites, no save. Isolated hex cage concept using Phaser 3. */
(() => {
  'use strict';
  const M=window.DigiFarmLabModel, status=document.getElementById('status');
  const buttons=['buy','feed','train','expand','zoomIn','zoomOut','reset'];
  const say=message=>{status.textContent=message;};
  if(!M||!window.Phaser){say('Phaser CDN 로드 실패. 인터넷 연결을 확인해.');return;}
  const hex=(cx,cy,r)=>Array.from({length:6},(_,i)=>{
    const a=Math.PI/6+i*Math.PI/3;return {x:cx+Math.cos(a)*r,y:cy+Math.sin(a)*r};
  });
  const centers=(row,col)=>({x:117+col*104+(row%2)*52,y:175+row*89});
  class CageScene extends Phaser.Scene{
    constructor(){super('Cages');}
    create(){
      this.state=M.initial();
      this.art=[];
      this.sprites=[];
      this.biting=new Set();
      this.dragStart=null;
      this.cameras.main.setBackgroundColor('#164e4d');
      this.cameras.main.setBounds(0,0,800,800);
      this.bindEvents();
      this.redraw('2행으로 시작 · 작은 육각형을 눌러 선택해.');
      window.DigiFarmLab={
        command:type=>this.command(type),
        reset:()=>{this.scene.restart();},
        zoom:dir=>{this.cameras.main.setZoom(
          Math.max(.75,Math.min(1.5,this.cameras.main.zoom+dir*.15)));this.redraw('배율 변경');},
        select:(r,c)=>this.select(r,c),
        snapshot:()=>JSON.parse(JSON.stringify(this.state))
      };
      buttons.forEach(id=>document.getElementById(id).disabled=false);
    }
    bindEvents(){
      this.input.on('pointerdown',pointer=>{
        this.dragStart={x:pointer.x,y:pointer.y,lastY:pointer.y,moved:false};
      });
      this.input.on('pointermove',pointer=>{
        const d=this.dragStart;
        if(!d||!pointer.isDown)return;
        if(Math.hypot(pointer.x-d.x,pointer.y-d.y)>8)d.moved=true;
        if(d.moved){
          const scale=this.cameras.main.zoom;
          const max=Math.max(0,130+this.state.rows*89-450/scale);
          this.cameras.main.scrollY=Math.max(0,Math.min(max,
            this.cameras.main.scrollY-(pointer.y-d.lastY)/scale));
        }
        d.lastY=pointer.y;
      });
      this.input.on('pointerup',pointer=>{
        const d=this.dragStart;this.dragStart=null;
        if(!d||d.moved)return;
        const at=this.cameras.main.getWorldPoint(pointer.x,pointer.y);
        let best=null,dist=Infinity;
        for(let row=0;row<this.state.rows;row++)for(let col=0;col<M.COLUMNS;col++){
          const c=centers(row,col),a=Math.hypot(c.x-at.x,c.y-at.y);
          if(a<dist){dist=a;best={row,col};}
        }
        if(best&&dist<53)this.select(best.row,best.col);
      });
    }
    select(row,col){
      const r=M.transition(this.state,{type:'select',row,col});
      if(r.changed){this.state=r.state;this.redraw(r.message);}
      return r;
    }
    command(type,at){
      const result=M.transition(this.state,{type,at});
      if(result.changed)this.state=result.state;
      this.redraw(result.message);
      if(type==='feed'&&result.changed){
        // Four distinct bites. Selection may change; food remains assigned to origin.
        const cageKey=this.state.selected;
        this.biting.add(cageKey);
        for(let i=1;i<=M.FOOD_BITES;i++)this.time.delayedCall(i*520,()=>{
          const next=M.transition(this.state,{type:'bite',at:cageKey});
          if(next.changed){this.state=next.state;this.redraw(next.message);}
          if(i===M.FOOD_BITES){this.biting.delete(cageKey);this.redraw('식사 완료 · 먹이 소멸');}
        });
      }
      return result;
    }
    redraw(message){
      this.art.forEach(obj=>obj.destroy());this.art=[];this.sprites=[];
      const add=obj=>{this.art.push(obj);return obj;};
      const g=add(this.add.graphics());
      // NDS-inspired mint honeycomb ground, all art generated by code.
      g.fillStyle(0x184e4f,1);g.fillRect(0,0,800,800);
      for(let r=0;r<9;r++)for(let c=0;c<10;c++){
        const p=centers(r,c),pts=hex(p.x,p.y,57);
        g.fillStyle((r+c)%2?0x205d58:0x1a5551,.58);g.fillPoints(pts,true);
      }
      const selected=this.state.selected;
      for(let row=0;row<this.state.rows;row++)for(let col=0;col<M.COLUMNS;col++){
        const p=centers(row,col),id=M.code(row,col);
        const cage=this.state.cages[id],isSelected=selected===id;
        const points=hex(p.x,p.y,49);
        g.fillStyle(cage?0x357b6d:0x284e52,.98);g.fillPoints(points,true);
        g.lineStyle(isSelected?5:2,isSelected?0xffdb85:cage?0xb2ded0:0x679993,1);
        g.strokePoints(points,true);
        g.lineStyle(1,0xa4c6ae,.20);
        g.strokePoints(hex(p.x,p.y,37),true);
        if(!cage){
          add(this.add.text(p.x,p.y-6,'+',{
            fontFamily:'sans-serif',fontSize:'34px',color:'#8caea8'
          }).setOrigin(.5));
        }else{
          const body=add(this.add.container(p.x,p.y+1));
          const shadow=this.add.ellipse(0,21,46,9,0x0b2c32,.55);
          const torso=this.add.ellipse(0,-3,35,39,row?0xbad1f5:0xffcb6b);
          const eyeL=this.add.circle(-8,-9,2,0x193846);
          const eyeR=this.add.circle(8,-9,2,0x193846);
          const feetL=this.add.rectangle(-10,18,9,6,0xe59d62);
          const feetR=this.add.rectangle(10,18,9,6,0xe59d62);
          body.add([shadow,feetL,feetR,torso,eyeL,eyeR]);
          this.sprites.push({body,baseY:p.y+1,id});
          if(cage.food>0){
            const scale=cage.food/M.FOOD_BITES;
            const food=add(this.add.ellipse(p.x+25,p.y+19,
              20*scale,12*scale,0xe06951));
            food.setStrokeStyle(1,0xffe7a1);
          }
        }
      }
      // Small HUD; most viewport stays as an interactive game field.
      g.fillStyle(0x0e383b,.92);g.fillRoundedRect(15,8,770,66,9);
      add(this.add.text(27,19,'케이지 '+Object.keys(this.state.cages).length+
        ' · '+this.state.rows+'행 · Bit '+this.state.credits,
        {fontSize:'19px',color:'#e1f7eb'}));
      const cage=this.state.cages[selected];
      const details=cage?
        '선택 '+selected+' · '+cage.name+' · 허기 '+cage.hunger+
          ' · 먹이 '+cage.food+'/'+M.FOOD_BITES:
        '선택 '+selected+' · 빈 케이지 칸 · 구입 가능';
      add(this.add.text(27,48,details+' · 훈련 '+this.state.training,
        {fontSize:'15px',color:'#e3d89f'}));
      if(message)say(message+' · '+(cage?'현재 '+cage.name:'빈 칸'));
    }
    update(time){
      for(const actor of this.sprites){
        if(actor.body.active)actor.body.y=actor.baseY+
          Math.sin(time/260+(actor.id==='0:0'?0:1.5))*2.2;
      }
    }
  }
  new Phaser.Game({
    type:Phaser.AUTO,width:800,height:450,parent:'farm',
    scale:{mode:Phaser.Scale.FIT,autoCenter:Phaser.Scale.CENTER_BOTH},
    render:{pixelArt:true,antialias:false},
    scene:[CageScene]
  });
  for(const type of ['buy','feed','train','expand']){
    const el=document.getElementById(type);
    el.addEventListener('click',()=>window.DigiFarmLab?.command(type));
  }
  document.getElementById('zoomIn').addEventListener('click',
    ()=>window.DigiFarmLab?.zoom(1));
  document.getElementById('zoomOut').addEventListener('click',
    ()=>window.DigiFarmLab?.zoom(-1));
  document.getElementById('reset').addEventListener('click',
    ()=>window.DigiFarmLab?.reset());
})();
